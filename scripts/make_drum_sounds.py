"""Cut the six sounds of Fabio's drum kit out of the CC0 samples in
assets/source/sounds and write them as C arrays (game/src/audio/drum_sounds.c),
mono, signed 16 bit, at the mixer rate. Needs ffmpeg.

    BOOM      the bass drum
    BADABOOM  snare, snare, bass drum
    TASH      a crash cymbal
    BODOBOOOM toms falling to a long bass drum
    BOING     a twang
    DISH      a snare and a closed cymbal
"""

import array
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "source" / "sounds"
OUT = ROOT / "game" / "src" / "audio" / "drum_sounds.c"
RATE = 22050


def load(name):
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(SOURCE / (name + ".flac")), "-ar", str(RATE),
         "-ac", "1", "-f", "s16le", "-"], check=True, capture_output=True).stdout
    samples = array.array("h")
    samples.frombytes(raw)
    return list(samples)


def mix(parts, seconds):
    """parts: (sample name, start in seconds, gain). Trimmed to `seconds`."""
    out = [0.0] * int(seconds * RATE)
    for name, start, gain in parts:
        offset = int(start * RATE)
        for i, v in enumerate(load(name)):
            if offset + i >= len(out):
                break
            out[offset + i] += v * gain
    peak = max(1.0, max(abs(v) for v in out))
    out = [v * 30000.0 / peak for v in out]
    fade = int(0.03 * RATE)
    for i in range(fade):
        out[len(out) - 1 - i] *= i / fade
    return [int(v) for v in out]


SOUNDS = [
    ("BOOM", [("drum_bass_hard", 0.0, 1.0)], 0.6),
    ("BADABOOM", [("drum_snare_hard", 0.0, 0.8), ("drum_snare_hard", 0.13, 0.9),
                  ("drum_bass_hard", 0.27, 1.2)], 0.9),
    ("TASH", [("drum_cymbal_hard", 0.0, 1.0)], 0.9),
    ("BODOBOOOM", [("drum_tom_hi_hard", 0.0, 0.9), ("drum_tom_mid_hard", 0.14, 0.9),
                   ("drum_tom_lo_hard", 0.28, 1.0), ("drum_heavy_kick", 0.28, 1.2)], 1.2),
    ("BOING", [("elec_twang", 0.0, 1.0)], 0.62),
    ("DISH", [("drum_snare_hard", 0.0, 0.7), ("drum_cymbal_closed", 0.0, 1.0)], 0.3),
]


def main():
    lines = ['/**', ' * @file drum_sounds.c', ' * @brief Generated by scripts/make_drum_sounds.py from CC0 samples; do not edit.',
             ' */', '#include "drum_sounds.h"', '']
    for name, parts, seconds in SOUNDS:
        data = mix(parts, seconds)
        lines.append("static const int16_t k%s[%d] = {" % (name.capitalize(), len(data)))
        for i in range(0, len(data), 16):
            lines.append("    " + ",".join(str(v) for v in data[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const drum_clip_t kDrumClips[DRUM_WORDS] = {")
    for name, parts, seconds in SOUNDS:
        lines.append('    {k%s, %d},' % (name.capitalize(), int(seconds * RATE)))
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, OUT.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()

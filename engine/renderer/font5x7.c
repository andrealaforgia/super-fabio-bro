static const glyph_t* find(char c) {
  char wanted = (char)toupper((unsigned char)c);
  for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++)
    if (glyphs[i].character == wanted) return &glyphs[i];
  return (const glyph_t*)0;
}

bool font5x7_has_glyph(char c) { return find(c) != (const glyph_t*)0; }

bool font5x7_pixel(char c, int row, int column) {
  const glyph_t* glyph = find(c);
  if (!glyph) glyph = find('?');
  if (row < 0 || row >= FONT5X7_HEIGHT || column < 0 || column >= FONT5X7_WIDTH)
    return false;
  return glyph->rows[row][column] == '#';
}
